def render_permissions() -> str:
    """The permission gate: kinds, prompter protocol and the headless no-op."""
    cases = "\n".join(f"    case {kind.case}" for kind in PERMISSION_KINDS)
    return f"""import Foundation

/// Every system prompt iOS can show. {DO_NOT_EDIT}
enum PermissionKind: String, CaseIterable {{
{cases}
}}

/// One concrete system prompt. Implementations live in `{PERMISSIONS_DIR}/` and are
/// only ever invoked through `Permissions.request(_:)`.
protocol PermissionPrompter {{
    static var kind: PermissionKind {{ get }}
    static func prompt() async -> Bool
}}

/// The single gate for permission prompts: a no-op returning `false` in headless
/// screen-id mode so no system alert can cover the captured screen.
enum Permissions {{
    @discardableResult
    static func request<P: PermissionPrompter>(_ prompter: P.Type) async -> Bool {{
        guard !Headless.isActive else {{ return false }}
        return await prompter.prompt()
    }}
}}
"""


def render_app(target: str, startup: list[str] | None = None, *, launch: bool = False) -> str:
    """``@main`` entry point wiring ``Router`` into ``RootView`` and starting the modules.

    With ``launch`` the entry point presents the launch screens once the modules started.
    """
    calls = (
        startup if startup is not None else ["Subscriptions.start()", "await Attribution.start()"]
    )
    if launch:
        calls = [*calls, "router.presentLaunch()"]
    task = "\n".join(f"                    {call}" for call in calls)
    return f"""import SwiftUI

/// App entry point. {DO_NOT_EDIT}
@main
struct {target}App: App {{
    @State private var router = Router.launch()

    var body: some Scene {{
        WindowGroup {{
            RootView()
                .environment(router)
                .onOpenURL {{ router.handle($0) }}
                .task {{
{task}
                }}
        }}
    }}
}}
"""


def render_pending(entry: ScreenEntry) -> str:
    """Compiling placeholder view until the screen task replaces it."""
    return f"""import SwiftUI

/// {clean_text(entry.name)} — placeholder until the screen task generates it.
struct {entry.type_name}: View {{
    var body: some View {{
        {PENDING_MARKER} {swift_str(entry.screen_id)})
    }}
}}
"""
